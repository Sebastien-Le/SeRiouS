copy_capsule_static_resources <- function(source_dir, appdir) {
  if (!dir.exists(source_dir)) {
    return(invisible(FALSE))
  }

  copy_dir <- function(from, to) {
    if (!dir.exists(from)) {
      return(invisible(FALSE))
    }

    dir.create(to, recursive = TRUE, showWarnings = FALSE)

    files <- list.files(
      from,
      all.files = TRUE,
      no.. = TRUE,
      full.names = TRUE
    )

    if (length(files) > 0) {
      file.copy(
        from = files,
        to = to,
        recursive = TRUE,
        overwrite = TRUE
      )
    }

    invisible(TRUE)
  }

  copy_dir(
    from = file.path(source_dir, "pdf"),
    to = file.path(appdir, "www", "pdf")
  )

  copy_dir(
    from = file.path(source_dir, "img"),
    to = file.path(appdir, "www", "img")
  )

  copy_dir(
    from = file.path(source_dir, "www"),
    to = file.path(appdir, "www")
  )

  copy_dir(
    from = file.path(source_dir, "data"),
    to = file.path(appdir, "data")
  )

  invisible(TRUE)
}

write_standalone_board_helpers <- function(file) {
  helper_functions <- c(
    "serious_board_step_ids",
    "serious_board_get_step",
    "serious_board_step_status",
    "serious_board_status_icon",
    "serious_board_status_label",
    "serious_board_status_border_color",
    "serious_board_section_id",
    "serious_board_default_section_colors",
    "serious_board_section_color",
    "serious_board_get_position",
    "serious_board_make_nodes",
    "serious_board_make_edges",
    "serious_board_widget"
  )

  ns <- environment(write_standalone_board_helpers)

  missing_functions <- helper_functions[
    !vapply(
      helper_functions,
      exists,
      logical(1),
      envir = ns,
      inherits = FALSE
    )
  ]

  if (length(missing_functions) > 0) {
    stop(
      "Cannot generate standalone board helpers. Missing functions: ",
      paste(missing_functions, collapse = ", "),
      call. = FALSE
    )
  }

  tmp <- tempfile(fileext = ".R")

  dump(
    list = helper_functions,
    file = tmp,
    envir = ns
  )

  lines <- readLines(tmp, warn = FALSE)

  writeLines(
    c(
      "# Standalone SeRiouS board helpers",
      "# Generated by write_capsule_app(). Do not edit by hand.",
      "",
      "`%||%` <- function(x, y) {",
      "  if (is.null(x)) y else x",
      "}",
      "",
      lines
    ),
    con = file
  )

  invisible(file)
}

